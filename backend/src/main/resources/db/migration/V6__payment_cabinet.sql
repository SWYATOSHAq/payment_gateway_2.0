ALTER TABLE payments
    ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN archived BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN needs_review BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE payments SET created_at = checkout_created_at WHERE checkout_created_at IS NOT NULL;

CREATE TABLE payment_tags (
    payment_id BIGINT NOT NULL REFERENCES payments (id) ON DELETE CASCADE,
    tag VARCHAR(40) NOT NULL,
    PRIMARY KEY (payment_id, tag)
);

CREATE INDEX payment_tags_tag_idx ON payment_tags (tag, payment_id);
CREATE INDEX payments_cabinet_created_idx ON payments (archived, created_at, id);
CREATE INDEX payments_cabinet_status_idx ON payments (status);
CREATE INDEX payments_cabinet_amount_idx ON payments (amount);
